const MATCHERS: { category: Category; keyword: string; token: boolean }[] = (
  Object.entries(CATEGORY_KEYWORDS) as [Category, string[]][]
).flatMap(([category, keywords]) =>
  keywords.map((keyword) => {
    const normalized = normalizeNameKey(keyword);

    return { category, keyword: normalized, token: !normalized.includes(" ") };
  }),
);

export const inferCategory = (name: string): Category => {
  const key = normalizeNameKey(name);
  const tokens = new Set(key.split(" "));

  let best: { category: Category; length: number } | null = null;

  for (const matcher of MATCHERS) {
    const matches = matcher.token
      ? tokens.has(matcher.keyword)
      : key.includes(matcher.keyword);

    if (matches && (best === null || matcher.keyword.length > best.length)) {
      best = { category: matcher.category, length: matcher.keyword.length };
    }
  }

  return best?.category ?? "Outros";
};
